void main() {
  int a = 10;
  int b = 4;

  // Operasi aritmatika dasar
  int penjumlahan = a + b;
  int pengurangan = a - b;
  int perkalian = a * b;
  double pembagian = a / b;
  int modulo = a % b;

  // Output hasil
  print('Penjumlahan: $a + $b = $penjumlahan');
  print('Pengurangan: $a - $b = $pengurangan');
  print('Perkalian: $a * $b = $perkalian');
  print('Pembagian: $a / $b = $pembagian');
  print('Modulo: $a % $b = $modulo');
}
